"""Train and score Prelude's risk gate with MLX LoRA on a Mac.

Reproduces the experiment end to end from files in this repository:

    python -m aria_code.training.prelude_train data  --out DIR
    python -m aria_code.training.prelude_train train --data DIR --adapter DIR/adapter
    python -m aria_code.training.prelude_train pick  --log DIR/train.log --adapter DIR/adapter
    python -m aria_code.training.prelude_train eval  --adapter DIR/adapter

``data`` uses only train-side splits (``dev`` and ``extra``). Variants of those commands
are generated by swapping arguments and wrapping them (``cd x &&``, ``time``, a pipe to
``tail``), labelled by ``safety.risk``, and a command that also appears in a test split
is dropped. Levels 3 and 4 are repeated so the loss weighs the dangerous cases.
``pick`` chooses a checkpoint by validation loss only. ``eval`` reports every split;
read ``test2`` as a score and never as a list of mistakes to fix.

Needs ``mlx-lm`` (Apple Silicon); it is imported only by ``train`` and ``eval``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from aria_code.training import prelude_eval as P

FILES = ["app.py", "src/main.rs", "README.md", "config.yaml", "docs/guide.md", "build/out.js", "tests/test_x.py",
         "data/prices.csv", "notes.txt", "src/index.ts", "lib/util.go", "scripts/run.sh", "output/report.pdf",
         "tmp/cache.bin", "web/app.css"]
PACKAGES = ["left-pad", "requests", "numpy", "zod", "serde", "rich", "pandas", "express", "tokio", "axios"]
BRANCHES = ["main", "dev", "feature/login", "fix/crash", "release/1.2"]
HOSTS = ["https://api.example.com/v1", "https://example.org/data.json", "https://files.test.io/pkg.tgz",
         "http://localhost:8080/health"]
WRAPPERS = [
    lambda c: c, lambda c: f"cd project && {c}", lambda c: f"time {c}", lambda c: f"{c} 2>&1",
    lambda c: f"{c} | tail -20", lambda c: f"cd src && {c}", lambda c: f"FOO=1 {c}", lambda c: f"{c} | head -5",
]
WEIGHT = {3: 3, 4: 2}  # how many times a level appears in the training file
VARIANTS_PER_FAMILY = 14
SEED = 7
MODEL_ENV = "ARIA_PRELUDE_BASE"


def vary(command: str, rng: random.Random) -> str:
    tokens = command.split(" ")
    for i, token in enumerate(tokens):
        if not i:
            continue
        if re.search(r"\.\w{1,4}$|/", token) and not token.startswith(("http", "-", "/dev", "~/.ssh", ".env")) \
                and ".pem" not in token and "credentials" not in token:
            tokens[i] = rng.choice(FILES)
        elif token in PACKAGES:
            tokens[i] = rng.choice(PACKAGES)
        elif token in BRANCHES:
            tokens[i] = rng.choice(BRANCHES)
        elif token.startswith("http") and "|" not in command:
            tokens[i] = rng.choice(HOSTS)
    return " ".join(tokens)


def record(command: str, level: int) -> dict:
    return {"messages": [{"role": "system", "content": P.RISK_SYSTEM}, {"role": "user", "content": command},
                         {"role": "assistant", "content": str(level)}]}


def is_validation(family: str) -> bool:
    return int(hashlib.sha256(family.encode()).hexdigest(), 16) % 10 == 3


def build_training_data() -> Tuple[List[dict], List[dict], dict]:
    """(train, validation, facts) from train-side splits only."""
    from aria_code.safety.risk import assess_command

    rng = random.Random(SEED)
    rows = P.load("risk")
    train_rows = [r for r in rows if r["split"] in ("dev", "extra")]
    held_out = {r["input"] for r in rows if r["split"] in ("test", "test2")}
    held_families = {r["family"] for r in rows if r["split"] in ("test", "test2")}
    bases: Dict[str, str] = {}
    for r in train_rows:
        bases.setdefault(re.sub(r"^(cd project && |time )", "", r["input"]), r["family"])
    variants: Dict[str, str] = {}
    counts: Dict[str, int] = {}
    for base, fam in bases.items():
        for _ in range(40):
            command = rng.choice(WRAPPERS)(vary(base, rng))
            if "\n" in command or command in variants:
                continue
            variants[command] = fam
            counts[fam] = counts.get(fam, 0) + 1
            if counts[fam] >= VARIANTS_PER_FAMILY:
                break
    pool = [(c, assess_command(c).level, f) for c, f in variants.items()]
    pool += [(r["input"], r["label"], r["family"]) for r in train_rows]
    seen, distinct = set(), []
    for command, level, fam in pool:
        if command in seen or command in held_out or fam in held_families or P.family(command) in held_families:
            continue
        seen.add(command)
        distinct.append((command, level, fam))
    train, valid = [], []
    for command, level, fam in distinct:
        if is_validation(fam):
            valid.append(record(command, level))
        else:
            train.extend(record(command, level) for _ in range(WEIGHT.get(level, 1)))
    rng.shuffle(train)
    return train, valid, {"distinct": len(distinct), "train_lines": len(train), "validation_lines": len(valid)}


def write_data(out: Path) -> dict:
    train, valid, facts = build_training_data()
    out.mkdir(parents=True, exist_ok=True)
    for name, data in (("train", train), ("valid", valid)):
        (out / f"{name}.jsonl").write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in data),
                                           encoding="utf-8")
    return facts


def base_model(explicit: Optional[str]) -> str:
    import os

    value = explicit or os.environ.get(MODEL_ENV)
    if value:
        return value
    cache = Path.home() / ".cache" / "huggingface" / "hub" / "models--Qwen--Qwen2.5-1.5B-Instruct" / "snapshots"
    found = sorted(cache.glob("*")) if cache.is_dir() else []
    if not found:
        raise SystemExit(f"Pass --model, or set {MODEL_ENV}, to a Qwen2.5-1.5B-Instruct directory or Hugging Face id.")
    return str(found[-1])


def train(data: Path, adapter: Path, model: Optional[str], iters: int, rate: float, layers: int) -> int:
    command = [sys.executable, "-m", "mlx_lm", "lora", "--model", base_model(model), "--train", "--data", str(data),
               "--adapter-path", str(adapter), "--iters", str(iters), "--batch-size", "4", "--num-layers", str(layers),
               "--learning-rate", str(rate), "--steps-per-eval", "100", "--val-batches", "42", "--save-every", "100",
               "--mask-prompt"]
    return subprocess.call(command)


def validation_losses(log: str) -> Dict[int, float]:
    text = re.sub(r"\x1b\[[0-9;]*m", "", log).replace("\r", "\n")
    return {int(m.group(1)): float(m.group(2)) for m in re.finditer(r"^\s*(\d+)\s+val\s+([\d.]+)", text, re.M)
            if int(m.group(1)) > 1}


def pick(log: Path, adapter: Path) -> int:
    losses = validation_losses(log.read_text(encoding="utf-8", errors="replace"))
    if not losses:
        raise SystemExit("No validation losses in the log.")
    step = min(losses, key=losses.get)
    checkpoint = adapter / f"{step:07d}_adapters.safetensors"
    if not checkpoint.is_file():
        raise SystemExit(f"Checkpoint for step {step} is missing: {checkpoint}")
    chosen = adapter.with_name(adapter.name + f"-best-{step}")
    chosen.mkdir(exist_ok=True)
    shutil.copy(adapter / "adapter_config.json", chosen / "adapter_config.json")
    shutil.copy(checkpoint, chosen / "adapters.safetensors")
    print(json.dumps({"step": step, "validation_loss": losses[step], "adapter": str(chosen)}))
    return 0


def evaluate(adapter: Optional[Path], model: Optional[str]) -> dict:
    from mlx_lm import generate, load

    network, tokenizer = load(base_model(model), adapter_path=str(adapter) if adapter else None)
    rows = P.load("risk")
    predictions = {}
    for row in rows:
        prompt = tokenizer.apply_chat_template(
            [{"role": "system", "content": P.RISK_SYSTEM}, {"role": "user", "content": row["input"]}],
            add_generation_prompt=True, tokenize=False)
        predictions[row["id"]] = P.parse_prediction("risk", generate(network, tokenizer, prompt=prompt, max_tokens=4))
    report = P.score("risk", rows, predictions)
    report.pop("confusion", None)
    return {"adapter": str(adapter) if adapter else None, **report}


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    d = sub.add_parser("data")
    d.add_argument("--out", required=True)
    t = sub.add_parser("train")
    t.add_argument("--data", required=True)
    t.add_argument("--adapter", required=True)
    t.add_argument("--model")
    t.add_argument("--iters", type=int, default=1000)
    t.add_argument("--rate", type=float, default=5e-5)
    t.add_argument("--layers", type=int, default=8)
    k = sub.add_parser("pick")
    k.add_argument("--log", required=True)
    k.add_argument("--adapter", required=True)
    e = sub.add_parser("eval")
    e.add_argument("--adapter")
    e.add_argument("--model")
    args = parser.parse_args(argv)
    if args.command == "data":
        print(json.dumps(write_data(Path(args.out))))
        return 0
    if args.command == "train":
        return train(Path(args.data), Path(args.adapter), args.model, args.iters, args.rate, args.layers)
    if args.command == "pick":
        return pick(Path(args.log), Path(args.adapter))
    print(json.dumps(evaluate(Path(args.adapter) if args.adapter else None, args.model), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
